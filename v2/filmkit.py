#!/usr/bin/env python3
"""Shared build helpers for the v2 trailer (v2/trailer60) and cutdown (v2/cutdown30).

Each film's build.py describes its edit once (footage segments, typed text, SFX cues) and calls
these helpers to write, from that single description:

  - v2/<film>/edit.json      the footage edit: film frame -> clip frame, per segment
  - v2/<film>/events.json    the SFX cue list for v2/music/score.py (film seconds)
  - the TIMING block inside v2/<film>/index.html (between the @generated markers), so the
    composition reads the same numbers as the score and the plate
  - out/v2/plates/<film>-plate.mp4 (with --plate): the footage section of the film as one 4K
    clip on film time (cuts, speed ramps and holds baked in, frame exact), read by the
    composition as assets/plate.mp4. HyperFrames has no playback-rate control, so the retime
    is done here.

Clip frames index v2/recording/cues.json times at 30 fps: frame n shows clip time n/30.
"""
import json
import math
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
FPS = 30
CUES = json.loads((REPO / "v2" / "recording" / "cues.json").read_text())


def cue_frame(name):
    """First clip frame on which cue `name` is drawn (cue time rounded up to the frame grid)."""
    return math.ceil(CUES[name] * FPS - 1e-6)


# ---------------------------------------------------------------- footage edit
def seg(f0, f1, s0, s1=None, note=""):
    """Film frames [f0, f1) show clip frames s0 .. s1 (inclusive), linearly; s1=None holds s0."""
    return {"film": [f0, f1], "src": [s0, s0 if s1 is None else s1], "note": note}


def frame_map(segments):
    """List of (film_frame, clip_frame) for every film frame the segments cover."""
    out = []
    for s in segments:
        f0, f1 = s["film"]
        a, b = s["src"]
        n = f1 - f0
        for k in range(n):
            src = a if n == 1 else a + (b - a) * k / (n - 1)
            out.append((f0 + k, int(math.floor(src + 0.5))))
    films = [f for f, _ in out]
    assert films == list(range(films[0], films[0] + len(films))), "segments must be contiguous"
    return out


def write_edit(film_dir, segments, extra=None):
    fm = frame_map(segments)
    doc = {
        "_note": "Generated by build.py. Footage edit: film frames [f0, f1) show clip frames "
                 "src[0]..src[1] of assets/footage.mp4 (linear; equal = hold). "
                 "Baked into assets/plate.mp4 (frame 0 = film frame film_start).",
        "fps": FPS,
        "film_start": fm[0][0],
        "film_end": fm[-1][0] + 1,
        "segments": [dict(s, speed=round((s["src"][1] - s["src"][0] + 1) / (s["film"][1] - s["film"][0]), 3)
                          if s["src"][1] != s["src"][0] else 0) for s in segments],
    }
    if extra:
        doc.update(extra)
    segs = doc.pop("segments")
    body = json.dumps(doc, indent=2)[:-2] + ',\n  "segments": [\n' + ",\n".join("    " + json.dumps(x) for x in segs) + "\n  ]\n}\n"
    (film_dir / "edit.json").write_text(body)
    return fm


def build_plate(footage, out, fm, crf=10):
    """Stream the 4K clip through and write each needed clip frame as many times as the edit asks."""
    W, H = 3840, 2160
    fsize = W * H * 3 // 2  # yuv420p
    need = [s for _, s in fm]
    assert all(b >= a for a, b in zip(need, need[1:])), "edit must be monotonic in clip time"
    out.parent.mkdir(parents=True, exist_ok=True)
    dec = subprocess.Popen(["ffmpeg", "-v", "error", "-i", str(footage), "-f", "rawvideo",
                            "-pix_fmt", "yuv420p", "-"], stdout=subprocess.PIPE)
    enc = subprocess.Popen(["ffmpeg", "-v", "error", "-y", "-f", "rawvideo", "-pix_fmt", "yuv420p",
                            "-s", f"{W}x{H}", "-r", str(FPS), "-i", "-", "-c:v", "libx264",
                            "-preset", "medium", "-crf", str(crf), "-pix_fmt", "yuv420p",
                            "-g", "15", "-movflags", "+faststart", str(out)], stdin=subprocess.PIPE)
    idx, k = 0, 0
    while k < len(need):
        buf = dec.stdout.read(fsize)
        if len(buf) < fsize:
            raise SystemExit(f"footage ended at frame {idx}, edit needs {need[k]}")
        while k < len(need) and need[k] == idx:
            enc.stdin.write(buf)
            k += 1
        idx += 1
    dec.stdout.close()
    dec.kill()
    enc.stdin.close()
    if enc.wait() != 0:
        raise SystemExit("plate encode failed")
    print(f"plate: {out} ({len(need)} frames, {len(need) / FPS:.3f} s)")


# ---------------------------------------------------------------- typing
def type_times(text, t0, per_char):
    """On-screen frame time of each character of `text` typed from t0 (one char per `per_char` s).
    A character appears on the first frame at or after its nominal time."""
    return [math.ceil((t0 + i * per_char) * FPS - 1e-6) / FPS for i in range(len(text))]


def tick_events(times, cue, skip=(" ",), text=None, gain_db=None):
    """One key tick per frame on which a (non-space) character appears."""
    seen, ev = set(), []
    for i, t in enumerate(times):
        if text is not None and text[i] in skip:
            continue
        if t in seen:
            continue
        seen.add(t)
        e = {"t": round(t, 4), "cue": cue}
        if gain_db is not None:
            e["gain_db"] = gain_db
        ev.append(e)
    return ev


# ---------------------------------------------------------------- outputs
def write_events(film_dir, events, note):
    events = sorted(events, key=lambda e: (e["t"], e["cue"]))
    doc = {"_note": note, "events": events}
    (film_dir / "events.json").write_text(
        "{\n  \"_note\": " + json.dumps(note) + ",\n  \"events\": [\n" +
        ",\n".join("    " + json.dumps(e) for e in events) + "\n  ]\n}\n")
    return doc


def inject_timing(index_html, timing):
    """Replace the generated TIMING block in index.html."""
    src = index_html.read_text()
    a = src.index("/*@generated:timing*/")
    b = src.index("/*@end:timing*/")
    block = ("/*@generated:timing*/\n  // Generated by build.py from the same numbers as events.json and edit.json. Do not edit.\n"
             "  var TIMING = " + json.dumps(timing, separators=(",", ":")) + ";\n  ")
    index_html.write_text(src[:a] + block + src[b:])


def main_flags():
    return set(sys.argv[1:])
