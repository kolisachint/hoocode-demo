#!/usr/bin/env python3
"""Cutdown 30 s: the edit, the SFX events and the composition timing, from one description.

    python3 v2/cutdown30/build.py            # edit.json, events.json, TIMING block in index.html
    python3 v2/cutdown30/build.py --plate    # also bake out/v2/plates/cutdown30-plate.mp4 (4K)

Then: python3 v2/music/score.py --film cutdown30 --events v2/cutdown30/events.json, render, mux
(README.md).
"""
import sys

sys.dont_write_bytecode = True
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import filmkit as fk  # noqa: E402

HERE = Path(__file__).resolve().parent
F = fk.FPS


def s(t):
    """film seconds -> film frame (rounded to the nearest frame)"""
    return round(t * F)


CARD1, Y1, CARD2, A2 = fk.cue_frame("CARD1"), fk.cue_frame("Y1"), fk.cue_frame("CARD2"), fk.cue_frame("A2")
Y3, EXIT0, LANDED = fk.cue_frame("Y3"), fk.cue_frame("EXIT0"), fk.cue_frame("LANDED")
DONE = fk.cue_frame("DONE")
EXIT0_SETTLED = EXIT0 + 5   # transcript settles 5 frames after EXIT0 (see trailer60/build.py)
TUI0 = 134                  # clip 4.45 s

A2_F = 278                  # first frame after the a keypress at 9.25 s (9.267 s)
SEGMENTS = [
    fk.seg(s(2.0), s(6.0), TUI0, TUI0 + s(4.0) - 1, "plans: TUI, plan, task panel (1x)"),
    fk.seg(s(6.0), s(7.5), CARD1, Y1 - 1, "card 1, Edit (1.7x); y lands on 7.5"),
    fk.seg(s(7.5), s(8.0), Y1, CARD2 - 1, "card 1 answered (slow)"),
    fk.seg(s(8.0), A2_F, CARD2, A2 - 1, "card 2, Shell (2x); a lands on 9.25"),
    fk.seg(A2_F, s(10.0), A2, None, "hold: card 2 answered, through the air gap"),
    fk.seg(s(10.0), s(12.0), EXIT0_SETTLED, DONE - 1, "exit 0, test result ok (0.72x)"),
    fk.seg(s(12.0), s(14.0), LANDED, LANDED + s(2.0) - 1, "LANDED (1x)"),
]

TASK = 'hoocode "Add a --json flag to the stats command"'
INSTALL = "curl -fsSL https://kolisachint.github.io/hoocode/install.sh | sh"
task_t = fk.type_times(TASK, 0.40, 0.030)
install_t = fk.type_times(INSTALL, 26.0, 1.2 / len(INSTALL))

BEATS = {
    "eye": 2 / 30, "enter": 1.95, "push_plan": 3.6,
    "card1": 6.0, "y1": 7.5, "card2": 8.0, "a2": 9.25, "gap": 9.875,
    "exit0": 10.0, "landed": 12.0,
    "breath": 14.0, "features": 16.0, "lockup": 22.0, "tagline": 24.0, "install": 26.0, "end": 28.0,
}

events = [{"t": round(BEATS["eye"], 4), "cue": "blip-eye"}]
events += fk.tick_events(task_t, "key-tick", text=TASK)
events += [
    {"t": BEATS["enter"], "cue": "key-enter"},
    {"t": BEATS["push_plan"], "cue": "whoosh-in", "dur": 0.4},
    {"t": BEATS["card1"], "cue": "blip-card"},
    {"t": BEATS["y1"], "cue": "key-press"}, {"t": BEATS["y1"], "cue": "spark-micro"},
    {"t": BEATS["card2"], "cue": "blip-card"},
    {"t": BEATS["a2"], "cue": "key-press"}, {"t": BEATS["a2"], "cue": "spark-micro"},
    {"t": BEATS["landed"], "cue": "chime-landed"},
    {"t": BEATS["breath"], "cue": "spark-sting-short"},
]
events += [{"t": 16.0 + 2.0 * i, "cue": "card-tick"} for i in range(3)]
events += [{"t": BEATS["lockup"], "cue": "spark-sting"}]
events += fk.tick_events(install_t, "key-tick-soft", text=INSTALL)
events += [{"t": BEATS["install"], "cue": "spark-micro"}]

if __name__ == "__main__":
    fm = fk.write_edit(HERE, SEGMENTS)
    fk.write_events(HERE, events,
                    "Generated by v2/cutdown30/build.py from v2/recording/cues.json and the edit "
                    "(edit.json). Film seconds. Cue vocabulary: v2/music/README.md.")
    timing = {"task": task_t, "install": install_t, "beats": BEATS,
              "plate": {"start": fm[0][0] / F, "end": (fm[-1][0] + 1) / F}}
    fk.inject_timing(HERE / "index.html", timing)
    print(f"events: {len(events)}; footage {timing['plate']}")
    if "--plate" in fk.main_flags():
        fk.build_plate(HERE / "assets" / "footage.mp4", fk.REPO / "out" / "v2" / "plates" / "cutdown30-plate.mp4", fm)
